CREATE TABLE users (
    user_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(50) NOT NULL UNIQUE,
    email           VARCHAR(100) NOT NULL UNIQUE,
    password_hash   VARCHAR(255) NOT NULL,
    shipping_addr   VARCHAR(255) NOT NULL,
    billing_addr    VARCHAR(255) NOT NULL
);

CREATE TABLE cards (
    card_number     VARCHAR(16) PRIMARY KEY,
    card_cvv        VARCHAR(4) NOT NULL,
    card_exp_date   DATE NOT NULL
);

CREATE TABLE user_cards (
    user_id         INT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    card_number     VARCHAR(16) NOT NULL REFERENCES cards(card_number) ON DELETE CASCADE,
    PRIMARY KEY (user_id, card_number)
);

CREATE TABLE sellers (
    seller_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         INT NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE,
    store_name      VARCHAR(100) NOT NULL,
    bank_acc_number VARCHAR(20) NOT NULL
);

CREATE TABLE items (
    item_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id       INT NOT NULL REFERENCES sellers(seller_id) ON DELETE CASCADE,
    name            VARCHAR(100) NOT NULL,
    description     TEXT NOT NULL,
    price           NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
    is_listed       BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE cart (
    user_id     INT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    item_id     INT NOT NULL REFERENCES items(item_id) ON DELETE CASCADE,
    quantity    INT NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (user_id, item_id)
);

CREATE TABLE orders (
    order_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      INT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    item_id      INT NOT NULL REFERENCES items(item_id),
    quantity     INT NOT NULL CHECK (quantity > 0),
    order_date   TIMESTAMPTZ NOT NULL DEFAULT now(),
    total        NUMERIC(10, 2) NOT NULL CHECK (total >= 0),  -- price * quantity at purchase time
    order_status VARCHAR(20) NOT NULL DEFAULT 'pending'
                 CHECK (order_status IN ('pending','shipped','delivered','cancelled'))
);

CREATE TABLE reviews (
    review_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    item_id     INT NOT NULL REFERENCES items(item_id) ON DELETE CASCADE,
    stars       INT NOT NULL CHECK (stars BETWEEN 1 AND 5),
    title       VARCHAR(100) NOT NULL,
    description TEXT NOT NULL,
    UNIQUE (user_id, item_id)
);

CREATE INDEX idx_user_cards_card ON user_cards(card_number);
CREATE INDEX idx_items_seller ON items(seller_id);
CREATE INDEX idx_orders_user  ON orders(user_id);
CREATE INDEX idx_orders_item  ON orders(item_id);
CREATE INDEX idx_reviews_item ON reviews(item_id);